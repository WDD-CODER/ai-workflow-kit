/**
 * The gate of one plan (or the run's final gate): the check commands run by script in one folder, each with a time
 * limit, and a receipt of what they printed (docs/agent/orchestrator.md "The run"). No model is involved.
 *
 *   import { gateCommands, runGate } from './lib/plan-gate.mjs'
 *   const commands = gateCommands({ prepare, pm, build, lint, test, manifest: true, extra, scope })
 *   const g = await runGate({ folder, commands, timeoutMin: 15, receipt: true })
 *   // g = { status: 'pass'|'fail'|'env', exit: 0|1|2, results: [{ command, exit, seconds, status, tail }], flaky, failed }
 *
 * Order: the `orchestrator.prepare` steps, the project checks (build, lint, testCi or test), the kit manifest check
 * when the project has a manifest, the plan's scope check, then the plan's own `[auto]` commands. The scope check and the
 * manifest check are trusted code from the main folder (scopeCheck() in this process; the main folder's
 * kit-manifest-check.mjs run against the plan's folder), never the copies on the branch under test. A command that ends
 * with an environment error (a busy file, a port in use, a network error, a command that could not start) runs once
 * more; passing then is a flake, failing again is `env` (exit 2: no fix round, the environment is checked). Any other
 * failure is `fail` (exit 1). The receipt `<folder>/.claude/gate-receipt.json` holds each command, its exit, seconds,
 * status and the last 50 lines of its output; the folder's git exclude lists it, so it is never committed.
 * Commands are run without a shell: `node …` with this node, `npm|pnpm run <script>` with the package manager (through
 * the shell on Windows only, where it is a .cmd shim; a script name is letters, digits and `:_-`).
 */
import { mkdirSync, writeFileSync, readFileSync, existsSync, appendFileSync } from 'node:fs'
import { join, dirname, isAbsolute } from 'node:path'
import { spawn, spawnSync } from 'node:child_process'
import { createRequire } from 'node:module'
import { extractScopeGlobs } from './plan-scope.mjs'

/** The gate line of the trusted scope check (run in this process from the main folder's scripts, never the branch's). */
export const scopeMarker = (base, plan) => `scope-check (kit copy) --diff=${base} --plan=${plan}`
// Regenerated by kit scripts: never a scope question (the same list as scope-check.mjs).
const GENERATED = ['.kit/install.json', 'docs/workflow-kit/kit-owned.json', 'docs/workflow-kit/manifest.json', 'docs/workflow-kit/manifest.md']

/**
 * The plan's scope, checked by trusted code: the files the folder changed against `base` (commits, staged, unstaged and
 * untracked) held to the Read-Write Scope of `planText` (the plan as the run branch holds it, so a builder cannot widen
 * its own scope) plus what every plan may touch (the plan file, `.claude/sessions/**`, `.worktree-*`, `docs/brain/**`,
 * the hotspots, the generated kit files). A kit-managed copy (`scripts/**`, `.claude/**`) a plan does not name is out,
 * like any other file. `upstream` globs are out even when named. Returns { exit, out } for the gate.
 */
export function scopeCheck({ folder, base, planText, planPath, hotspots = [], upstream = [] }) {
  const picomatch = createRequire(import.meta.url)('picomatch')
  const globs = extractScopeGlobs(planText ?? '')
  if (!globs) return { exit: 1, out: `SCOPE_CHECK: ${planPath} has no readable scope under "## Read-Write Scope"` }
  const slash = (p) => (p.endsWith('/') ? `${p}**` : p)
  const isMatch = picomatch([planPath, '.claude/sessions/**', '.worktree-*', 'docs/brain/**', ...hotspots.filter(Boolean).map(slash), ...GENERATED, ...globs], { dot: true })
  const isUpstream = upstream.length ? picomatch(upstream.map(slash), { dot: true }) : () => false
  const lines = (...a) => String(spawnSync('git', a, { cwd: folder, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }).stdout ?? '').split('\n').map((l) => l.trim()).filter(Boolean)
  const files = [...new Set([
    ...lines('diff', '--name-only', '--no-renames', `${base}...HEAD`), ...lines('diff', '--name-only', '--no-renames', '--cached'),
    ...lines('diff', '--name-only', '--no-renames'), ...lines('ls-files', '--others', '--exclude-standard'),
  ].map((f) => f.replace(/\\/g, '/')))]
  const out = files.filter((f) => isUpstream(f) || !isMatch(f))
  return out.length
    ? { exit: 1, out: [...out.map((f) => `SCOPE: ${isUpstream(f) ? 'upstream' : 'out'} ${f}`), `SCOPE_CHECK: ${out.length} file(s) outside ${planPath}'s Read-Write Scope`].join('\n') }
    : { exit: 0, out: `SCOPE: ok — ${files.length} changed file(s) inside the scope` }
}

/** Output that names an environment problem, not a code problem. */
export const ENV_FAIL_RE = /\b(EBUSY|EPERM|EACCES|ENOSPC|EADDRINUSE|ECONNRESET|ECONNREFUSED|EAI_AGAIN|ENOTFOUND|EMFILE)\b|socket hang up|getaddrinfo/
export const RECEIPT_REL = '.claude/gate-receipt.json'
export const TAIL_LINES = 50

/** Split a command into words the way the plans write them (plain words and "double quotes"). */
export function words(cmd) {
  const out = []
  const re = /"([^"]*)"|'([^']*)'|(\S+)/g
  let m
  while ((m = re.exec(String(cmd)))) out.push(m[1] ?? m[2] ?? m[3])
  return out
}

/**
 * The gate's command list, deduplicated, in order. `prepare` = orchestrator.prepare entries; `build`/`lint`/`test` =
 * npm script names (testCi wins over test); `manifest` adds the kit manifest check; `scope` = { plan, base } adds the
 * plan's scope check against the run branch; `extra` = the plan's own [auto] commands (already allowed).
 */
export function gateCommands({ prepare = [], pm = 'npm', build = '', lint = '', test = '', testCi = '', manifest = false, kitRoot = null, scope = null, extra = [] } = {}) {
  const run = (s) => (typeof s === 'string' && s !== '' ? `${pm} run ${s}` : null)
  const prep = (Array.isArray(prepare) ? prepare : [])
    .filter((p) => p && typeof p.missing === 'string' && typeof p.script === 'string')
    .map((p) => `node scripts/orch-state.mjs prepare --missing ${p.missing} --script ${p.script}${typeof p.in === 'string' && p.in !== '' && p.in !== '.' ? ` --in ${p.in}` : ''}${pm === 'pnpm' ? ' --pm pnpm' : ''}`)
  const list = [
    ...prep,
    run(build), run(lint), run(testCi || test),
    // The policy checks come from the main folder's scripts (kitRoot), never from the branch under test: a builder that
    // edits its own copy cannot pass them. The manifest check reads the folder it runs in.
    manifest ? (kitRoot ? `node "${String(kitRoot).replace(/\\/g, '/')}/scripts/kit-manifest-check.mjs"` : 'node scripts/kit-manifest-check.mjs') : null,
    scope ? scopeMarker(scope.base, scope.plan) : null,
    ...extra,
  ].filter(Boolean).map((c) => String(c).trim())
  return [...new Set(list)]
}

/** The program and arguments a command runs as, or null when it is not a shape the gate runs. */
export function commandArgv(cmd, pm = 'npm') {
  const w = words(cmd)
  if (w[0] === 'node') return { file: process.execPath, args: w.slice(1), shell: false }
  if ((w[0] === 'npm' || w[0] === 'pnpm') && w[1] === 'run' && /^[A-Za-z0-9:_-]+$/.test(w[2] ?? '') && w.length === 3) {
    // Windows: npm is a .cmd shim, so it runs through the shell as one string (the script name is a safe word).
    return process.platform === 'win32' ? { file: `${w[0]} run ${w[2]}`, args: [], shell: true } : { file: w[0], args: ['run', w[2]], shell: false }
  }
  return null
}

/** Run one command in `cwd` with a time limit; resolves { exit, seconds, out, timedOut, startError }. */
export function runCommand(cmd, cwd, timeoutMs, env = process.env) {
  return new Promise((done) => {
    const argv = commandArgv(cmd)
    const started = Date.now()
    const secs = () => Math.round((Date.now() - started) / 100) / 10
    if (!argv) {
      done({ exit: 1, seconds: 0, out: `not a command the gate runs: ${cmd}`, timedOut: false, startError: false })
      return
    }
    let child
    try {
      child = spawn(argv.file, argv.args, { cwd, env, shell: argv.shell, windowsHide: true })
    } catch (e) {
      done({ exit: null, seconds: secs(), out: e.message, timedOut: false, startError: true })
      return
    }
    let out = ''
    let timedOut = false
    const timer = setTimeout(() => {
      timedOut = true
      try {
        if (process.platform === 'win32' && child.pid) spawnSync('taskkill', ['/PID', String(child.pid), '/T', '/F'], { windowsHide: true })
        else child.kill('SIGKILL')
      } catch { /* gone */ }
    }, timeoutMs)
    child.stdout.on('data', (d) => { out += d })
    child.stderr.on('data', (d) => { out += d })
    child.on('error', (e) => {
      clearTimeout(timer)
      done({ exit: null, seconds: secs(), out: `${out}\n${e.message}`, timedOut, startError: true })
    })
    child.on('close', (code) => {
      clearTimeout(timer)
      done({ exit: code, seconds: secs(), out, timedOut, startError: false })
    })
  })
}

const tailOf = (s, n = TAIL_LINES) => String(s ?? '').replace(/\r\n/g, '\n').split('\n').map((l) => l.trimEnd()).filter((l) => l.trim()).slice(-n).join('\n')
/** pass, fail or env-fail for one finished command. */
function statusOf(r) {
  if (r.exit === 0 && !r.timedOut) return 'pass'
  if (r.startError) return 'env-fail'
  if (r.timedOut) return 'fail'
  return ENV_FAIL_RE.test(tailOf(r.out, 20)) ? 'env-fail' : 'fail'
}

/** Keep the receipt out of git: the repository's (shared) exclude file lists it once. */
function excludeReceipt(folder) {
  const r = spawnSync('git', ['rev-parse', '--git-common-dir'], { cwd: folder, encoding: 'utf8' })
  const dir = String(r.stdout ?? '').trim()
  if (r.status !== 0 || !dir) return
  const file = join(isAbsolute(dir) ? dir : join(folder, dir), 'info', 'exclude')
  try {
    const now = existsSync(file) ? readFileSync(file, 'utf8') : ''
    if (!now.split(/\r?\n/).includes(RECEIPT_REL)) {
      mkdirSync(dirname(file), { recursive: true })
      appendFileSync(file, `${now && !now.endsWith('\n') ? '\n' : ''}${RECEIPT_REL}\n`)
    }
  } catch { /* the receipt may then show as untracked; it is never committed by the script */ }
}

/**
 * Run the commands in order in `folder`. Every command runs (a failure does not stop the next one), so the receipt and
 * a fix round see every failing check at once. `onResult(result)` is called after each command (the caller's calls.csv).
 */
export async function runGate({ folder, commands, timeoutMin = 15, receipt = true, onResult = null, env = process.env, builtins = {} }) {
  const results = []
  const flaky = []
  const timeoutMs = Math.max(1, Number(timeoutMin) || 15) * 60_000
  // `builtins`: a gate line run in this process (the trusted scope check) → () => { exit, out }.
  const run = async (command) => {
    if (typeof builtins[command] !== 'function') return runCommand(command, folder, timeoutMs, env)
    const started = Date.now()
    const b = await builtins[command]()
    return { exit: b.exit, seconds: Math.round((Date.now() - started) / 100) / 10, out: b.out, timedOut: false, startError: false }
  }
  for (const command of commands) {
    let r = await run(command)
    let status = statusOf(r)
    let seconds = r.seconds
    if (status === 'env-fail') {
      const again = await run(command)
      seconds += again.seconds
      const st = statusOf(again)
      if (st === 'pass') flaky.push(command)
      r = again
      status = st
    }
    const row = { command, exit: r.exit, seconds: Math.round(seconds * 10) / 10, status, ...(r.timedOut ? { timedOut: true } : {}), tail: tailOf(r.out) }
    if (r.timedOut) row.tail = `${row.tail}\ntimed out after ${timeoutMin} min`.trim()
    results.push(row)
    if (onResult) onResult(row)
  }
  const failed = results.filter((x) => x.status === 'fail')
  const env_ = results.filter((x) => x.status === 'env-fail')
  const status = !commands.length ? 'fail' : failed.length ? 'fail' : env_.length ? 'env' : 'pass'
  const exit = status === 'pass' ? 0 : status === 'env' ? 2 : 1
  const head = spawnSync('git', ['rev-parse', 'HEAD'], { cwd: folder, encoding: 'utf8' })
  const out = { status, exit, head: head.status === 0 ? String(head.stdout).trim() : null, results, flaky, failed: [...failed, ...env_].map((x) => x.command) }
  if (receipt) {
    try {
      excludeReceipt(folder)
      mkdirSync(join(folder, '.claude'), { recursive: true })
      writeFileSync(join(folder, RECEIPT_REL), `${JSON.stringify({ at: new Date().toISOString(), ...out }, null, 2)}\n`)
    } catch { /* a folder that cannot take the file still has the answer */ }
  }
  return out
}
